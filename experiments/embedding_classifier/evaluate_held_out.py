"""Score a trained classifier bundle against the project's frozen human
annotation release (loaded via ``src.gold_release``).

The weak-label dev split (printed by ``train.py``) is known to be optimistic
because it is generated by the same keyword rules it is scored against.
This script reads the separately-maintained human annotation release
instead, which the training code never touches.

Usage:
    .venv/bin/python -m experiments.embedding_classifier.evaluate_held_out \
        --model outputs/embedding_classifier_run1/model.joblib
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")

import joblib
from sklearn.metrics import confusion_matrix

from src.gold_release import load_frozen_gold
from src.quality import ASPECTS, CLASSIFIER_TARGETS, classification_metrics
from experiments.embedding_classifier.train import predict_texts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    args = parser.parse_args(argv)

    held_out, _ = load_frozen_gold()
    bundle = joblib.load(args.model)
    prediction = predict_texts(bundle, held_out.text.tolist())
    report = classification_metrics(held_out, prediction)

    print("=== 独立人工标注评测分数（不是弱标签验证集分数）===")
    for key in ("subjective_aspect_f1", "subjective_polarity_f1",
                "subjective_joint_accuracy", "subjective_recall"):
        target = CLASSIFIER_TARGETS[key]
        value = report[key]
        status = "达标" if value is not None and value >= target else "未达标"
        print(f"{key}: {value:.4f}  (目标 {target}, {status})")
    print("objective_precision:", report["objective_precision"],
          "objective_recall:", report["objective_recall"])

    subjective = held_out.subjectivity.eq("subjective")
    cm = confusion_matrix(held_out.loc[subjective, "aspect"], prediction.loc[subjective, "aspect"],
                          labels=ASPECTS)
    print()
    print("方面混淆矩阵(行=真实, 列=预测):")
    print("      " + " ".join(f"{label[:4]:>5}" for label in ASPECTS))
    for row_label, row in zip(ASPECTS, cm):
        print(f"{row_label[:5]:>5} " + " ".join(f"{value:>5}" for value in row))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
